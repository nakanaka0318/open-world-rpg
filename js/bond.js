Bond.html = function (id) {
  let h = _bondHtml.call(this, id);
  if (isAdult(id)) {
    const note = isLover(id) ? `恋人 ♥ ／ ${ADULT_AGE[id]}歳 ／ 奥義1.5倍・ステータス+20%・マイホームでデートに誘える`
      : canConfess(id) ? `マイホームで「${RING.n}」を渡すと、告白イベントで恋人(絆Lv11)になれる`
      : `${ADULT_AGE[id]}歳 ／ 絆Lv10でエピソードを全部見たあと、「${RING.n}」を渡すと恋人(絆Lv11)になれる`;
    h += `<div class="sc-note"><small>${note}</small></div>`;
  }
  return h;
};
