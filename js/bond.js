const Bond = {
  // 絆ポイントを足す。レベルが上がったら toast で知らせる
  gain(id, n, quiet) {
    const c = G.roster[id];
    if (!c) return;
    c.bond = c.bond || { lv: 1, exp: 0, ep: 0 };
    const b = c.bond;
    if (b.lv >= BOND_MAX) return;
    b.exp += n;
    let up = false;
    while (b.lv < BOND_MAX && b.exp >= bondNeed(b.lv)) { b.exp -= bondNeed(b.lv); b.lv++; up = true; }
    if (b.lv >= BOND_MAX) b.exp = 0;
    if (up && !quiet) UI.toast(`♥ ${CHARS[id].n} の絆レベルが ${b.lv} になった!${BOND_EP_LV.includes(b.lv) ? '<br>マイホームでエピソードが見られる' : ''}`, 2200);
    if (b.lv >= BOND_MAX && !G.skins[id + '@bond']) { G.skins[id + '@bond'] = 1; if (!quiet) UI.toast(`${CHARS[id].n} の衣装「絆のドレス」を手に入れた!`, 2600); }
  },
  // まだ見ていないエピソードがあるか
  pendingEp(id) { const b = bondOf(id); const n = BOND_EP_LV.filter(l => b.lv >= l).length; return (b.ep || 0) < n && BOND_EP[id] ? b.ep || 0 : -1; },
  async playEp(id) {
    const k = this.pendingEp(id);
    if (k < 0) return false;
    const c = G.roster[id];
    const lines = BOND_EP[id][k];
    Sound.play('star4');
    await UI.say(`♥ 絆エピソード ${k + 1}「${CHARS[id].n}」`);
    await UI.say(lines, { name: CHARS[id].n, look: charLook(id) });
    c.bond.ep = k + 1;
    if (k === 2) await UI.say(`${CHARS[id].n} との絆が最大になった!\n衣装「絆のドレス」${CHARS[id].rar === 5 ? 'と、奥義の威力1.3倍' : ''}がもらえた。`);
    Game.autoSave();
    return true;
  },
  hearts(id) {
    const b = bondOf(id);
    const pct = b.lv >= BOND_MAX ? 100 : Math.floor(100 * b.exp / bondNeed(b.lv));
    return `<span class="bond"><b>♥ 絆Lv${b.lv}</b><i><u style="width:${pct}%"></u></i>${b.lv >= BOND_MAX ? '<small>MAX</small>' : ''}</span>`;
  },
  html(id) {
    const b = bondOf(id);
    return `<div class="st-sec">絆 <small class="dim">(戦闘・マイホームでの会話・プレゼントで上がる)</small></div><div class="sc-note">${this.hearts(id)} ステータス+${Math.round((bondStatMul(id) - 1) * 100)}% ／ エピソード ${b.ep || 0}/3 ／ 好きなもの: ${GIFTS[GIFT_FAV[id]] ? GIFTS[GIFT_FAV[id]].n : '?'}<br><small class="dim">Lv3・6・10でエピソード。Lv10で衣装「絆のドレス」${CHARS[id].rar === 5 ? '、奥義の威力1.3倍' : ''}</small></div>`;
  },
};

