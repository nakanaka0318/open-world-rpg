function bondNeed(lv) { return 20 + lv * 15; }
function bondOf(id) { const r = G && G.roster[id]; return r && r.bond ? r.bond : { lv: 1, exp: 0, ep: 0 }; }
function bondStatMul(id) { return 1 + 0.02 * (bondOf(id).lv - 1); }
function bondUltMul(id) { return bondOf(id).lv >= BOND_MAX ? 1.3 : 1; }

