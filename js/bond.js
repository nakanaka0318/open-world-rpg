function isAdult(id) { return !!ADULT_AGE[id]; }
function canConfess(id) { const b = bondOf(id); return isAdult(id) && ROMANCE[id] && b.lv === BOND_MAX && (b.ep || 0) >= 3; }
function isLover(id) { return bondOf(id).lv >= LOVE_LV; }
bondUltMul = function (id) { const lv = bondOf(id).lv; return lv >= LOVE_LV ? 1.5 : lv >= BOND_MAX ? 1.3 : 1; };

Object.assign(Bond, {
  // 指輪を渡す (告白イベント)
  async confess(id) {
    const c = G.roster[id], R = ROMANCE[id];
    const opt = { name: CHARS[id].n, look: charLook(id) };
    await UI.say(`${CHARS[id].n}に「${RING.n}」を差し出した。`);
    Sound.play('star5');
    await UI.say(R.conf, opt);
    c.bond.lv = LOVE_LV; c.bond.exp = 0;
    for (const k of skinsOf(id)) if (SKINS[k].lover) G.skins[k] = 1;
    await UI.say(`♥ ${CHARS[id].n} と恋人になった!\nステータス+20%、奥義の威力1.5倍。\n衣装「バニースーツ」「ビキニ」「夜会のドレス」を手に入れた!`);
    Game.autoSave(true);
  },
  async date(id) {
    const c = G.roster[id];
    const opt = { name: CHARS[id].n, look: charLook(id) };
    if (c.dateT && G.playtime - c.dateT < TALK_CD * 2) { await UI.say('「また今度ね。楽しみにしてる!」', opt); return; }
    const si = await UI.ask('どこに行く?', DATE_SPOTS.map(s => s.n).concat(['やめる']));
    if (si < 0 || si >= DATE_SPOTS.length) return;
    c.dateT = G.playtime;
    const s = DATE_SPOTS[si];
    c.dates = c.dates || {};
    Sound.play('heal');
    await UI.say(s.intro.replace('{n}', CHARS[id].n));
    await UI.say([ROMANCE[id].date, U.pick(ROMANCE[id].talk)], opt);
    if (!c.dates[si]) { c.dates[si] = 1; G.stones += 100; Game.hud(); await UI.say(`はじめてのデート「${s.n}」の思い出に、星晶石×100を手に入れた。`); }
    Game.autoSave();
  },
});
